  const DICTS = { zh: ZH, en: EN };
  let cur = 'zh';

  function t(key, params) {
    const d = DICTS[cur] || ZH;
    let s = d[key];
    if (s == null) s = ZH[key];
    if (s == null) return key;
    if (params) {
      Object.keys(params).forEach(function (k) {
        s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k]);
      });
    }
    return s;
  }
  t.set = function (lang) { cur = DICTS[lang] ? lang : 'zh'; };
  t.get = function () { return cur; };
  t.isEn = function () { return cur === 'en'; };
  /** 取双语字段：pick({zh:'..',en:'..'}) */
  t.pick = function (o) { return o && typeof o === 'object' ? (o[cur] != null ? o[cur] : o.zh) : o; };
  t.dict = function () { return DICTS[cur]; };

  window.I18N = t;
