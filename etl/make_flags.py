# -*- coding: utf-8 -*-
"""由 flag-icons 的 4x3 SVG 生成本地 flags.css（data URI，离线可用）。
用法: python etl/make_flags.py <flag-icons 解压目录> <iso 列表文件> <输出 css>
"""
import os
import re
import sys

def minify(svg):
    svg = re.sub(r'<\?xml[^>]*\?>', '', svg)
    svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)
    svg = re.sub(r'<!/\[CDATA\[.*?\]\]>', '', svg, flags=re.S)
    svg = re.sub(r'>\s+<', '><', svg)
    svg = re.sub(r'\s{2,}', ' ', svg)
    svg = svg.strip()
    return svg

def enc(s):
    s = s.replace('%', '%25')
    s = s.replace('#', '%23')
    s = s.replace('<', '%3C')
    s = s.replace('>', '%3E')
    s = s.replace('"', "'")
    s = s.replace('\n', '').replace('\r', '').replace('\t', '')
    s = s.replace('{', '%7B').replace('}', '%7D')
    s = s.replace('\\', '%5C')
    return s

def main():
    src = sys.argv[1]
    isof = sys.argv[2]
    out = sys.argv[3]
    isos = [l.strip().lower() for l in open(isof, encoding='utf-8') if l.strip()]
    parts = []
    miss = []
    total = 0
    for iso in isos:
        p = os.path.join(src, 'flags', '4x3', iso + '.svg')
        if not os.path.exists(p):
            miss.append(iso)
            continue
        raw = open(p, encoding='utf-8', errors='replace').read()
        m = minify(raw)
        total += len(m)
        parts.append('.fi-%s{background-image:url("data:image/svg+xml,%s")}' % (iso, enc(m)))
    head = (
        '/* AUTO-GENERATED by etl/make_flags.py — 本地国旗（flag-icons 4x3，离线可用） */\n'
        '.fi{position:relative;display:inline-block;width:1.4em;height:1.05em;'
        'vertical-align:-.18em;background-size:100% 100%;background-position:50% 50%;'
        'background-repeat:no-repeat;background-color:var(--flag-bg,#e9e9ee);'
        'border-radius:2px;box-shadow:0 0 0 1px rgba(0,0,0,.14) inset;flex:none}\n'
        '.fi.f-lg{width:1.8em;height:1.35em}\n'
        '.fi.f-sm{width:1.15em;height:.86em}\n'
        '.flag-fb{display:inline-block;font-size:.72em;font-weight:700;letter-spacing:.4px;'
        'color:var(--text-3);border:1px solid var(--line);border-radius:3px;padding:0 3px}\n'
    )
    with open(out, 'w', encoding='utf-8') as f:
        f.write(head)
        f.write('\n'.join(parts))
        f.write('\n')
    print('written %s: %d flags, raw svg %d KB, css %d KB' %
          (out, len(parts), total // 1024, os.path.getsize(out) // 1024))
    if miss:
        print('MISSING:', ' '.join(miss))

main()
